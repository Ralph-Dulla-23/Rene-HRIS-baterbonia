import assert from 'node:assert/strict';
import { INITIAL_ORIENTATION_DECK_CONFIG, getStoredOrientationDeckConfig, calculateQuizScore, validateOrientationDeckConfig, saveStoredOrientationDeckConfig, getCurrentOrientationAnswers, getOrientationQuizKey } from '../src/components/nho/nhoInitialData';
import { canAccessModule } from '../src/auth/roleAccess';

let saved = '';
Object.assign(globalThis, { window: { dispatchEvent() {} }, localStorage: { getItem: () => saved || null, setItem: (_key: string, value: string) => { saved = value; } } });
saved = JSON.stringify({ ...INITIAL_ORIENTATION_DECK_CONFIG, quizStages: undefined, quizQuestions: undefined });
const legacy = getStoredOrientationDeckConfig();
assert.equal(legacy.quizStages?.length, 4, 'Legacy decks retain established four parts');
assert.equal(legacy.quizQuestions?.length, 6, 'Legacy decks receive existing questions');
const config = structuredClone(legacy);
config.quizQuestions = config.quizQuestions!.slice(0, 4).map((q, idx) => ({ ...q, id: idx + 10, stageId: idx + 1, correctOptionIndex: 0 }));
config.quizStages = config.quizStages!.map(stage => ({ ...stage, questionCount: 1 }));
config.passingScorePct = 75;
assert.deepEqual(validateOrientationDeckConfig(config), []);
assert.deepEqual(calculateQuizScore({0: 0, 1: 0, 2: 0, 3: 1}, config), {score: 3, total: 4, percentage: 75, passed: true});
assert.equal(calculateQuizScore({0: 0, 1: 0}, config).passed, false);
assert.ok(validateOrientationDeckConfig({...config, quizQuestions: config.quizQuestions.map((q, i) => i ? q : {...q, question: ''})}).length);
assert.ok(validateOrientationDeckConfig({...config, quizQuestions: config.quizQuestions.map((q, i) => i ? q : {...q, correctOptionIndex: 9})}).length);
assert.ok(validateOrientationDeckConfig({...config, quizStages: config.quizStages.map((s, i) => i ? s : {...s, questionCount: 2})}).length);
assert.ok(validateOrientationDeckConfig({...config, quizStages: config.quizStages.map(s => ({...s, triggerAfterSlide: 7}))}).length);
assert.ok(validateOrientationDeckConfig({...config, quizQuestions: config.quizQuestions.map((q, i) => i ? q : {...q, stageId: 99})}).length);
assert.equal(saveStoredOrientationDeckConfig(config), true);
assert.deepEqual(getStoredOrientationDeckConfig().quizQuestions, config.quizQuestions);
assert.deepEqual(getCurrentOrientationAnswers({orientationQuizAnswers: {0: 1}}, config), {}, 'Edited questions invalidate old index-based answers');
assert.deepEqual(getCurrentOrientationAnswers({orientationQuizAnswers: {0: 1}, orientationQuizConfigKey: getOrientationQuizKey(config)}, config), {0: 1}, 'Current quiz answers resume normally');
const previousSaved = saved;
assert.equal(saveStoredOrientationDeckConfig({...config, passingScorePct: NaN}), false);
assert.equal(saved, previousSaved, 'Invalid drafts cannot replace a published quiz');
const originalError = console.error;
console.error = () => {};
globalThis.localStorage.setItem = () => { throw new Error('Storage full'); };
assert.equal(saveStoredOrientationDeckConfig(config), false, 'Persistence failure is reported');
console.error = originalError;
for (const role of ['TA', 'HR', 'HR Admin', 'Super Admin'] as const) assert.equal(canAccessModule(role, 'Orientation Settings'), true);
for (const role of ['Employee', 'IT', 'WFM', 'Trainer'] as const) assert.equal(canAccessModule(role, 'Orientation Settings'), false);
assert.equal(canAccessModule('TA', 'Recruitment Settings'), false);
console.log('PASS orientation config defaults, editing, scoring, validation, persistence and role isolation');
